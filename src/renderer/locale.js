/** Translate a key for a locale, falling back to English then the key itself. */
export function t(key, locale = 'en') {
  return translate(MESSAGES, key, locale);
}

// audit M20: "1 note … were never saved", "15 ملاحظات", "5 كلمة". A counted sentence has one
// form per plural category of its language (English: one, other; Arabic: zero, one, two, few,
// many, other), written in the catalog as `key#form`. The category comes from Intl.PluralRules.
const pluralRules = new Map();
export function pluralCategory(n, locale = 'en') {
  const lang = locale in MESSAGES ? locale : 'en';
  if (!pluralRules.has(lang)) pluralRules.set(lang, new Intl.PluralRules(lang));
  return pluralRules.get(lang).select(Math.abs(n));
}

/** The form of `key` for the number `n`; the plain key when `n` is no number or has no form. */
export function tPlural(key, n, locale = 'en') {
  if (typeof n === 'number' && Number.isFinite(n)) {
    const formKey = `${key}#${pluralCategory(n, locale)}`;
    const form = translate(MESSAGES, formKey, locale);
    if (form !== formKey) return form;
  }
  return t(key, locale);
}

/**
 * Fill `{name}`-style placeholders in a catalog template. Unknown vars render as
 * empty (never the literal `{key}`), so a missing variable can't leak keys to the UI.
 */
export function formatMessage(template, vars = {}) {
  return String(template == null ? '' : template).replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k];
    return v == null ? '' : String(v);
  });
}
